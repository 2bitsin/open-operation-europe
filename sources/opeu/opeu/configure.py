"""The entry (entry.cpp) with its include roots; main.cpp, the screen, the embedded resources and their test. All under
the warnings gate.

What is compiled in follows the tree: assets.embed/ (the 26 data files) and packs.embed/ (the classic pack and any
remaster) are embedded by buildutil when present and simply absent from the public mirror. This script writes, on
every configure, the header embedded.cpp reads them through, "opeu-embedded/resources.hpp": with either directory it
includes buildutil's accessor and says which of the two are there; with neither it is an empty accessor of the same
shape. A build tree reused after a directory disappears therefore never trusts a stale generated accessor."""
import buildutil_configure as bc

opeu = bc.source_dir().parent
# A finished module compiles under the warnings gate (docs/building.md "Warnings").
WARNINGS = ["-Wall", "-Wextra", "-Wconversion", "-Wsign-conversion", "-Wshadow", "-Werror"]
# The headers the entry reads unqualified: port.hpp and glue.hpp, the services,
# the platform layer, the recovered game's core/app.hpp and the opening's intro.hpp.
roots = ["glue/include", "services", "platform", "game/common", "game", "intro"]
for source in sorted(bc.source_dir().glob("*.cpp")):
  includes = [f"-I{opeu / root}" for root in roots] if source.name == "entry.cpp" else []
  bc.declare(source, options=WARNINGS + includes)

data = (bc.source_dir() / "assets.embed").is_dir()
pack = (bc.source_dir() / "packs.embed").is_dir()
# Adding or removing either directory reconfigures.
bc.depends(bc.source_dir())
HEADER = """// Generated by sources/opeu/opeu/configure.py on every configure: what this build embeds.
#pragma once

{accessor}

namespace opeu::app::detail::embedded_resources {{
inline constexpr auto DATA_EMBEDDED{{ {data} }};
inline constexpr auto PACK_EMBEDDED{{ {pack} }};
}}
"""
ACCESSOR = '#include "opeu-opeu/resources.hpp"'
NONE = """#include <cstddef>
#include <span>
#include <string_view>

// Nothing embedded: an accessor of buildutil's shape that holds no file.
namespace opeu::resources {
struct Resource {
  std::string_view     name;
  std::string_view     mime;
  unsigned char const* data;
  std::size_t          size;
};
inline auto all() noexcept -> std::span<Resource const> {
  return {};
}
}"""
bc.emit("opeu-embedded/resources.hpp", HEADER.format(accessor=ACCESSOR if data or pack else NONE, data=str(data).lower(), pack=str(pack).lower()))
