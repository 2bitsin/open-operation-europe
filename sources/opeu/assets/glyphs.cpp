auto DecodeGlyphs(Bytes const bytes) -> Decoded<std::vector<Image>> {
  if (bytes.size() % GLYPH_BYTES != 0) return std::unexpected{ DecodeError::BAD_SIZE };
  auto glyphs{ std::vector<Image>{} };
  for (auto const record : Chunks(bytes, GLYPH_BYTES)) {
    auto glyph{ DecodeBitmap(record, GLYPH_WIDTH / 8, GLYPH_HEIGHT) };
    if (!glyph) return std::unexpected{ glyph.error() };
    glyphs.push_back(*std::move(glyph));
  }
  return glyphs;
}

auto EndingGlyphCodes() noexcept -> std::span<unsigned const, ENDING_GLYPHS> {
  return ENDING_CODES;
}

