#!/usr/bin/env python3
"""Golden reference capture of the original OPEN.EXE intro under DOSBox-X.

Runs the untouched original launch path (KOEI.COM -> FMDRV.COM -> OPEN.EXE)
from a scratch copy of binaries/, records video (AVI/ZMBV), the mixer output
(WAV) and the raw OPL register stream (DRO v2) with DOSBox-X's DX-CAPTURE
command, then cuts the video into native 640x480 PNG frames with emulated
timestamps and a list of held scenes for comparison with the native port.

Two runs are made by default:

  full  no key at all; DOSBox-X is stopped by -time-limit --full-seconds
        (default 240 s). The unskipped intro loops forever (the title
        returns 0 and opeu_open_main starts over), and AUTOTYPE clamps its
        -w wait to 30 s, so a time limit is the only unattended way out.
        DOSBox-X shuts down cleanly at the limit (the AVI, WAV and DRO are
        all closed and readable).
  skip  AUTOTYPE presses space --skip-key-at seconds (default 12 s, max 30)
        after it runs, which is a few hundred ms before OPEN starts; shows
        the aborted path with the short title, after which OPEN exits,
        KOEI runs the stub MAIN (exit code 100) and quits by itself.

Outputs (under --out, default build/reports/open-dosbox):

  <run>/game/            scratch copy of binaries/ mounted as C:
  <run>/dosbox-x.conf    the generated configuration
  <run>/capture/         raw DOSBox-X captures (*.avi, *.wav, *.dro)
  <run>/frames/          t%07d_ms.png frames (native 640x480)
  <run>/frames.json      per-PNG index (ms, video frame number, md5)
  <run>/scenes.json      held scenes (identical frames for >= 300 ms)
  <run>/timeline.json    every distinct-frame change (ms, md5)

The "full" run's frames/ and scenes.json are also mirrored at the top level
of --out (frames/, scenes.json); the skip run lives in skip/.

Only the Python standard library, dosbox-x and ffmpeg/ffprobe are used.
"""

import argparse
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys
import time
import zlib

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
WIDTH, HEIGHT = 640, 480
FRAME_BYTES = WIDTH * HEIGHT * 3

# MAIN.EXE and END.EXE are replaced in the scratch copy by a 5-byte program
# "mov ax,4C64h / int 21h" (DOS loads by signature, so a COM image named .EXE
# runs). KOEI.COM treats MAIN's exit code 100 as "quit": it restores the text
# mode, unloads FMDRV and exits, which ends DX-CAPTURE and finalises the files.
EXIT_100 = bytes([0xB8, 0x64, 0x4C, 0xCD, 0x21])


def log(msg):
    print("[dosbox-open] " + msg, flush=True)


def png_bytes(rgb, w, h):
    """Encode packed RGB24 rows as a PNG (stdlib only)."""
    stride = w * 3
    raw = bytearray()
    for y in range(h):
        raw.append(0)
        raw += rgb[y * stride:(y + 1) * stride]

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(bytes(raw), 6))
            + chunk(b"IEND", b""))


def write_conf(path, game_dir, cap_dir, cycles, key_at, oplemu):
    autotype = ""
    if key_at is not None:
        # AUTOTYPE's wait runs on emulated time; KOEI and OPEN start within a
        # few hundred ms of this line, so key_at is ~ seconds into OPEN.
        autotype = "AUTOTYPE -w %g -p 0.5 space\n" % key_at
    text = f"""# generated by port/open/tests/dosbox_open_capture.py
[sdl]
output=surface
autolock=false
[log]
logfile=
[dosbox]
machine=svga_s3
memsize=16
captures={cap_dir}
show recorded filename=false
capture format=avi-zmbv
[cpu]
core=normal
cputype=386
cycles=fixed {cycles}
[render]
frameskip=0
aspect=false
scaler=none
[mixer]
nosound=false
rate=49716
[midi]
mpu401=none
mididevice=none
[sblaster]
sbtype=none
oplmode=opl2
oplemu={oplemu}
oplrate=49716
[gus]
gus=false
[speaker]
pcspeaker=true
tandy=off
disney=false
[serial]
serial1=disabled
serial2=disabled
[dos]
xms=true
ems=true
umb=true
[autoexec]
mount c "{game_dir}"
c:
{autotype}DX-CAPTURE /V /A /O KOEI
exit
"""
    with open(path, "w") as f:
        f.write(text)


def prepare_game(game_dir):
    if os.path.isdir(game_dir):
        shutil.rmtree(game_dir)
    os.makedirs(game_dir)
    src = os.path.join(REPO, "binaries")
    for name in sorted(os.listdir(src)):
        p = os.path.join(src, name)
        if os.path.isfile(p) and not name.endswith(".exo"):
            shutil.copy2(p, os.path.join(game_dir, name))
    # Every program the launcher runs after the opening (the game and the
    # ending: every .EXE but OPEN's) becomes the exit-100 stub.
    for stub in sorted(os.listdir(game_dir)):
        if stub.upper().endswith(".EXE") and stub.upper() != "OPEN.EXE":
            with open(os.path.join(game_dir, stub), "wb") as f:
                f.write(EXIT_100)


def run_dosbox(run_dir, cycles, key_at, limit, oplemu):
    game_dir = os.path.join(run_dir, "game")
    cap_dir = os.path.join(run_dir, "capture")
    prepare_game(game_dir)
    if os.path.isdir(cap_dir):
        shutil.rmtree(cap_dir)
    os.makedirs(cap_dir)
    conf = os.path.join(run_dir, "dosbox-x.conf")
    write_conf(conf, game_dir, cap_dir, cycles, key_at, oplemu)
    env = dict(os.environ)
    env.setdefault("SDL_VIDEODRIVER", "dummy")
    env.setdefault("SDL_AUDIODRIVER", "dummy")
    cmd = ["dosbox-x", "-conf", conf, "-fastlaunch", "-nomenu", "-nopromptfolder",
           "-time-limit", str(limit)]
    log("running: " + " ".join(cmd) + "  (SDL_VIDEODRIVER=%s SDL_AUDIODRIVER=%s)"
        % (env["SDL_VIDEODRIVER"], env["SDL_AUDIODRIVER"]))
    t0 = time.time()
    with open(os.path.join(run_dir, "dosbox-x.log"), "w") as lf:
        subprocess.run(cmd, cwd=run_dir, env=env, stdout=lf, stderr=subprocess.STDOUT,
                       timeout=limit + 120)
    log("dosbox-x finished in %.1f s host time" % (time.time() - t0))
    with open(os.path.join(run_dir, "dosbox-x.log"), errors="replace") as lf:
        events = [l.strip() for l in lf if "captur" in l.lower() or "Raw Opl" in l]
    return cap_dir, events


def capture_order(cap_dir, events):
    """AVI files in the order DOSBox-X started them (from its log)."""
    order = []
    for e in events:
        if "Started capturing video to:" in e:
            order.append(os.path.basename(e.split("to:", 1)[1].strip()))
    names = [n for n in order if os.path.exists(os.path.join(cap_dir, n))]
    for n in sorted(os.listdir(cap_dir)):
        if n.endswith(".avi") and n not in names:
            names.append(n)
    return names


def probe(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-count_packets",
                          "-show_entries", "stream=width,height,r_frame_rate,nb_read_packets",
                          "-of", "json", path], capture_output=True, text=True, check=True)
    s = json.loads(out.stdout)["streams"][0]
    num, den = s["r_frame_rate"].split("/")
    return int(s["width"]), int(s["height"]), int(num) / int(den), int(s["nb_read_packets"])


def extract(run_dir, cap_dir, events, every_ms, hold_ms):
    frames_dir = os.path.join(run_dir, "frames")
    if os.path.isdir(frames_dir):
        shutil.rmtree(frames_dir)
    os.makedirs(frames_dir)
    avis = capture_order(cap_dir, events)
    files = []
    timeline = []          # (ms, md5, video_frame) at every change
    index = []             # PNGs written
    channel_values = set()
    rule_misses = {k: [] for k in DAC_RULES}   # changed frames with bytes outside a rule
    t_start = 0.0          # running emulated time of the start of each AVI
    gframe = 0
    last_hash = None
    last_png_ms = None
    first_vga_ms = None
    first_nonblack_ms = None
    black = None
    for name in avis:
        path = os.path.join(cap_dir, name)
        w, h, fps, n = probe(path)
        files.append({"file": name, "width": w, "height": h, "fps": fps, "frames": n,
                      "start_ms": round(t_start * 1000, 3)})
        log("%s: %dx%d %.6f fps %d frames, starts at %.1f ms" % (name, w, h, fps, n,
                                                                    t_start * 1000))
        if (w, h) != (WIDTH, HEIGHT):
            # Not mode 12h (DOS text before KOEI's mode set, or after exit):
            # no PNGs, but a marker so no held scene runs across it.
            timeline.append([round(t_start * 1000, 3), "mode-%dx%d" % (w, h), gframe])
            t_start += n / fps
            gframe += n
            last_hash = None
            continue
        if black is None:
            black = bytes(FRAME_BYTES)
        proc = subprocess.Popen(["ffmpeg", "-v", "error", "-i", path, "-f", "rawvideo",
                                 "-pix_fmt", "rgb24", "-fps_mode", "passthrough", "-"],
                                stdout=subprocess.PIPE, bufsize=FRAME_BYTES * 4)
        k = 0
        while True:
            buf = proc.stdout.read(FRAME_BYTES)
            if len(buf) < FRAME_BYTES:
                break
            ms = (t_start + k / fps) * 1000.0
            if first_vga_ms is None:
                first_vga_ms = ms
            digest = hashlib.md5(buf).hexdigest()
            changed = digest != last_hash
            if changed:
                timeline.append([round(ms, 3), digest, gframe + k])
                if buf != black and first_nonblack_ms is None:
                    first_nonblack_ms = ms
                extra = buf.translate(None, bytes(sorted(channel_values)))
                channel_values.update(extra)
                for rk, good in DAC_RULES.items():
                    if buf.translate(None, good):
                        rule_misses[rk].append(round(ms, 3))
            if changed or last_png_ms is None or ms - last_png_ms >= every_ms - 0.5:
                fn = "t%07d_ms.png" % int(round(ms))
                p = os.path.join(frames_dir, fn)
                if not os.path.exists(p):
                    with open(p, "wb") as f:
                        f.write(png_bytes(buf, WIDTH, HEIGHT))
                    index.append({"ms": round(ms, 3), "frame": gframe + k, "png": fn,
                                  "md5": digest, "changed": changed})
                last_png_ms = ms
            last_hash = digest
            k += 1
        proc.wait()
        if k != n:
            log("warning: %s decoded %d frames, ffprobe said %d" % (name, k, n))
        t_start += k / fps
        gframe += k
        last_hash = None
    end_ms = t_start * 1000.0
    # Held scenes: runs of identical frames lasting >= hold_ms.
    scenes = []
    for i, (ms, digest, fr) in enumerate(timeline):
        nxt = timeline[i + 1][0] if i + 1 < len(timeline) else end_ms
        if nxt - ms >= hold_ms and not digest.startswith("mode-"):
            png = "t%07d_ms.png" % int(round(ms))
            scenes.append({"start_ms": ms, "end_ms": round(nxt, 3),
                           "duration_ms": round(nxt - ms, 3), "md5": digest,
                           "black": None, "png": "frames/" + png,
                           "cut_by_capture_end": i + 1 == len(timeline)})
    black_md5 = hashlib.md5(bytes(FRAME_BYTES)).hexdigest()
    for s in scenes:
        s["black"] = s["md5"] == black_md5
    meta = {"timestamp_origin": "first captured video frame = DX-CAPTURE start, just before "
                                "KOEI.COM runs (emulated time, frames concatenated across AVIs)",
            "files": files, "end_ms": round(end_ms, 3),
            "first_640x480_ms": first_vga_ms, "first_nonblack_ms": first_nonblack_ms}
    with open(os.path.join(run_dir, "frames.json"), "w") as f:
        json.dump({"meta": meta, "frames": index}, f, indent=1)
    with open(os.path.join(run_dir, "timeline.json"), "w") as f:
        json.dump({"meta": meta, "changes": timeline}, f, indent=1)
    with open(os.path.join(run_dir, "scenes.json"), "w") as f:
        json.dump({"meta": meta, "hold_ms": hold_ms, "scenes": scenes}, f, indent=1)
    return meta, scenes, channel_values, rule_misses, len(index)


# Candidate 6-bit DAC -> 8-bit expansions. Every changed 640x480 frame is
# checked against each: all of its bytes must lie in the rule's 64-value image.
DAC_RULES = {
    "(x<<2)|(x>>4)": bytes(sorted({(x << 2) | (x >> 4) for x in range(64)})),
    "x*255//63": bytes(sorted({x * 255 // 63 for x in range(64)})),
    "round(x*255/63)": bytes(sorted({int(x * 255 / 63 + 0.5) for x in range(64)})),
    "x<<2": bytes(sorted({x << 2 for x in range(64)})),
}


def collect_audio(run_dir, cap_dir):
    out = {}
    for n in sorted(os.listdir(cap_dir)):
        p = os.path.join(cap_dir, n)
        if n.endswith(".wav"):
            import array
            import wave
            with wave.open(p) as w:
                rate, ch, nfr = w.getframerate(), w.getnchannels(), w.getnframes()
                pcm = array.array("h", w.readframes(nfr))
            # Sound onsets: 10 ms windows with peak-to-peak > 512 after >= 500 ms
            # of near silence (peak-to-peak < 64, DC drift allowed).
            win = rate // 100 * ch
            onsets, quiet = [], 50
            for i in range(0, len(pcm) - win, win):
                seg = pcm[i:i + win]
                p2p = max(seg) - min(seg)
                if p2p > 512 and quiet >= 50:
                    onsets.append(round(i // ch * 1000.0 / rate, 1))
                quiet = quiet + 1 if p2p < 64 else 0
            out[n] = {"bytes": os.path.getsize(p), "rate": rate, "channels": ch,
                      "duration_ms": round(nfr * 1000.0 / rate, 3),
                      "sound_onsets_ms": onsets[:20]}
        elif n.endswith(".dro"):
            with open(p, "rb") as f:
                d = f.read()
            sig, major, minor, pairs, ms = struct.unpack("<8sHHII", d[:20])
            out[n] = {"bytes": len(d), "format": "%s v%d.%d" % (sig.decode(), major, minor),
                      "register_writes": pairs, "length_ms": ms,
                      "complete": len(d) == 26 + d[25] + pairs * 2,
                      "note": "DRO time 0 = first OPL note; see the WAV's first_sound_ms"}
    return out


def do_run(args, name, key_at, limit):
    run_dir = os.path.join(args.out, name)
    os.makedirs(run_dir, exist_ok=True)
    if not args.reuse:
        cap_dir, events = run_dosbox(run_dir, args.cycles, key_at, limit, args.oplemu)
        with open(os.path.join(run_dir, "capture-events.txt"), "w") as f:
            f.write("\n".join(events) + "\n")
    else:
        cap_dir = os.path.join(run_dir, "capture")
        with open(os.path.join(run_dir, "capture-events.txt")) as f:
            events = f.read().splitlines()
    meta, scenes, values, misses, npng = extract(run_dir, cap_dir, events, args.every_ms,
                                                 args.hold_ms)
    rule = {k: {"changed_frames_outside_rule": len(v), "at_ms": v[:5]}
            for k, v in misses.items()}
    vals = sorted(values)
    audio = collect_audio(run_dir, cap_dir)
    summary = {"run": name, "key_at_s": key_at, "time_limit_s": limit,
               "cycles": args.cycles, "pngs": npng,
               "meta": meta, "palette_rule_fits": rule, "observed_channel_values": vals,
               "audio": audio, "scenes": len(scenes)}
    with open(os.path.join(run_dir, "summary.json"), "w") as f:
        json.dump(summary, f, indent=1)
    log("%s: %d PNGs, %d held scenes, first 640x480 frame %.1f ms, first non-black %.1f ms"
        % (name, npng, len(scenes), meta["first_640x480_ms"] or -1,
           meta["first_nonblack_ms"] or -1))
    log("palette rule fits: %s" % rule)
    return run_dir


def mirror(src_run, out):
    for n in ("frames", "scenes.json", "frames.json", "timeline.json"):
        dst = os.path.join(out, n)
        if os.path.islink(dst) or os.path.isfile(dst):
            os.remove(dst)
        elif os.path.isdir(dst):
            shutil.rmtree(dst)
        os.symlink(os.path.relpath(os.path.join(src_run, n), out), dst)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(REPO, "build", "reports", "open-dosbox"))
    ap.add_argument("--runs", default="full,skip", help="comma list of full,skip")
    ap.add_argument("--cycles", type=int, default=20000)
    ap.add_argument("--oplemu", default="default")
    ap.add_argument("--full-seconds", type=int, default=240,
                    help="-time-limit for the unattended full run")
    ap.add_argument("--skip-key-at", type=float, default=12.0)
    ap.add_argument("--limit", type=int, default=420, help="dosbox-x -time-limit seconds")
    ap.add_argument("--every-ms", type=float, default=100.0)
    ap.add_argument("--hold-ms", type=float, default=300.0)
    ap.add_argument("--reuse", action="store_true", help="re-extract existing captures only")
    args = ap.parse_args()
    args.out = os.path.abspath(args.out)
    for tool in ("dosbox-x", "ffmpeg", "ffprobe"):
        if shutil.which(tool) is None:
            sys.exit("missing tool: " + tool)
    os.makedirs(args.out, exist_ok=True)
    runs = args.runs.split(",")
    if "full" in runs:
        full = do_run(args, "full", None, args.full_seconds)
        mirror(full, args.out)
    if "skip" in runs:
        do_run(args, "skip", args.skip_key_at, args.limit)


if __name__ == "__main__":
    main()
