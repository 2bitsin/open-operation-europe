#!/usr/bin/env python3
"""Generate port/open/open_image.c: where each recovered OPEN data object lives.

OPEN's initial DGROUP DS:0092..1973 is exactly the six recovered data modules
src/open/data/od*.c (their objects tile the range); the song bank of
src/open/data/ofmusic.c is the far data at frame 0710:0002. The port compiles
those modules natively (as part of opeu_open_recovered) and port/open/
open_memory.c copies each object to its address. This table gives only the
addresses and sizes:

  - DGROUP objects and offsets: the MODULES table of
    tests/validate_open_dgroup_data.py, which the gate checks against the DOS
    objects compiled from src/open/data (export names and DS offsets) and
    whose native sizes and initializer bytes it checks against the original;
  - the bank: tracks, voices and events in declaration order from 0710:0002
    (src/open/data/ofmusic.c header; tests/validate_open_ofmusic.py).

The native sizes are measured here by compiling a probe that includes the
data modules and prints sizeof of every object; a mismatch with the table
stops the generator. No byte comes from the original executable.

    python3 port/open/tools/gen_open_image.py [--check]
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT/'port/open/open_image.c'
sys.path.insert(0, str(ROOT/'tests'))
sys.path.insert(0, str(ROOT/'tools'))
from validate_open_dgroup_data import MODULES  # noqa: E402

BANK = (('opeu_music_tracks', 0x0002), ('opeu_music_voices', None), ('opeu_music_events', None))


def measure(names, files):
    cc = os.environ.get('CC', 'cc')
    probe = ''.join(f'#include "{f}"\n' for f in files)
    probe += '#include <stdio.h>\nint main(void){\n'
    probe += ''.join(f'  printf("%lu\\n", (unsigned long)sizeof({n}));\n' for n in names)
    probe += '  return 0;\n}\n'
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp)/'probe.c'
        exe = Path(tmp)/'probe'
        src.write_text(probe)
        subprocess.run([cc, '-std=c99', '-w', '-I', str(ROOT/'src/common'), str(src), '-o', str(exe)], check=True)
        out = subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout.split()
    return [int(v) for v in out]


def build():
    data_files = [str(ROOT/'src/open/data'/f'{m.lower()}.c') for m, _, _, _ in MODULES]
    entries = []
    for module, first, end, objects in MODULES:
        for name, offset, size in objects:
            entries.append((name, 0, offset, size, module))
    names = [e[0] for e in entries]
    sizes = measure(names, data_files)
    for (name, _, _, size, module), native in zip(entries, sizes):
        if native != size:
            raise SystemExit(f'{module}: {name} is {native} bytes natively, the DGROUP map says {size}')
    bank_sizes = measure([n for n, _ in BANK], [str(ROOT/'src/open/data/ofmusic.c')])
    offset = BANK[0][1]
    for (name, _), size in zip(BANK, bank_sizes):
        entries.append((name, 0x0710, offset, size, 'OFMUSIC'))
        offset += size
    return entries


def render(entries):
    lines = [
        '/* Generated by port/open/tools/gen_open_image.py -- do not edit.',
        ' *',
        ' * Addresses of the recovered OPEN data objects (src/open/data, compiled',
        ' * natively into opeu_open_recovered): seg 0 = DGROUP offset, otherwise a',
        ' * segment relative to OPEN\'s load segment. port/open/open_memory.c copies',
        ' * each object there. */',
        '#include "open_process.h"',
        '',
    ]
    for name, *_ in entries:
        lines.append(f'extern unsigned char {name}[];')
    lines += ['', 'const OpenImageObject open_image_objects[] = {']
    module = None
    for name, seg, off, size, mod in entries:
        if mod != module:
            module = mod
            lines.append(f'    /* {mod} */')
        lines.append(f'    {{ {name}, 0x{seg:04x}u, 0x{off:04x}u, {size}u, "{name}" }},')
    lines += ['};', '', f'const unsigned open_image_object_count = {len(entries)};', '']
    return '\n'.join(lines)


def main(argv):
    text = render(build())
    if '--check' in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT.relative_to(ROOT)} is stale: run port/open/tools/gen_open_image.py')
            return 1
        print(f'{OUT.relative_to(ROOT)}: current')
        return 0
    OUT.write_text(text)
    print(f'wrote {OUT.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
