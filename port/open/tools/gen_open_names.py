#!/usr/bin/env python3
"""Generate port/open/open_names.h: link names for the recovered OPEN.EXE code.

OPEN.EXE and the game (MAIN) were separate DOS programs, so their recovered sources
reuse names (opeu_mouse_reset, opeu_music_start, opeu_picture_handle, ...)
with different host signatures and data. The port links both into one
executable, so every external symbol that a src/open module *defines* is
renamed by a forced-include header: `#define opeu_x open_opeu_x`. Symbols that
src/open only *references* (opeu_string_length, opeu_copy_bytes: MAIN's
STRINGS and MEMORY objects, which the original OPEN.EXE linked unchanged) keep
their names and resolve to MAIN's recovered modules, as in the original link.

The list is taken from the host compiler's symbol table of each src/open
module (cc -c, nm), so it covers exactly what the modules define.

    python3 port/open/tools/gen_open_names.py [--check] [--src DIR]

--check compares with the checked-in header and fails when it is stale.
"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT/'port/open/open_names.h'


def modules(src):
    return sorted(p for d in ('core', 'data', 'io') for p in (src/'open'/d).glob('*.c'))


def symbols(src):
    cc = os.environ.get('CC', 'cc')
    defined, undefined = {}, set()
    with tempfile.TemporaryDirectory() as tmp:
        for path in modules(src):
            obj = Path(tmp)/(path.stem+'.o')
            subprocess.run([cc, '-std=c99', '-c', '-w', '-I', str(src/'common'), str(path), '-o', str(obj)],
                           check=True)
            out = subprocess.run(['nm', '-g', str(obj)], capture_output=True, text=True, check=True).stdout
            for line in out.splitlines():
                parts = line.split()
                if len(parts) == 2 and parts[0] == 'U':
                    undefined.add(parts[1].lstrip('_') if sys.platform == 'darwin' else parts[1])
                elif len(parts) == 3:
                    name = parts[2][1:] if sys.platform == 'darwin' and parts[2].startswith('_') else parts[2]
                    defined.setdefault(name, path.relative_to(src).as_posix())
    return defined, sorted(u for u in undefined - set(defined) if 'stack_chk' not in u)


def render(defined, undefined):
    lines = [
        '/* Generated by port/open/tools/gen_open_names.py -- do not edit.',
        ' *',
        ' * Forced include (-include) of every src/open module and of the port files',
        ' * that call into them: the external symbols the recovered OPEN.EXE modules',
        ' * define get an open_ prefix so that they do not collide with MAIN\'s',
        ' * recovered symbols of the same name in the one native executable.',
        ' *',
        ' * Referenced by src/open but defined elsewhere (not renamed): ' + ', '.join(
            u for u in undefined if 'stack_chk' not in u),
        ' */',
        '#ifndef OPEU_OPEN_NAMES_H',
        '#define OPEU_OPEN_NAMES_H',
        '',
    ]
    width = max(len(n) for n in defined)
    current = None
    for name in sorted(defined, key=lambda n: (defined[n], n)):
        if defined[name] != current:
            current = defined[name]
            lines.append(f'/* {current} */')
        lines.append(f'#define {name:<{width}} open_{name}')
    lines += ['', '#endif', '']
    return '\n'.join(lines)


def main(argv):
    src = ROOT/'src'
    if '--src' in argv:
        src = Path(argv[argv.index('--src')+1]).resolve()
    defined, undefined = symbols(src)
    text = render(defined, undefined)
    if '--check' in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'{OUT.relative_to(ROOT)} is stale: run port/open/tools/gen_open_names.py')
            return 1
        print(f'{OUT.relative_to(ROOT)}: {len(defined)} renamed symbols, current')
        return 0
    OUT.write_text(text)
    print(f'wrote {OUT.relative_to(ROOT)}: {len(defined)} symbols; referenced elsewhere: {", ".join(undefined)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
