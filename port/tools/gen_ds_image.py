#!/usr/bin/env python3
"""Generate port/gen/data_image.c: where the recovered data modules' objects
live in the original 16-bit address layout.

The data modules under src/main/data define DGROUP and FAR_DATA contents as
ordinary C objects whose byte layout tests/validate_far_data.py proves equal
to the DOS build. The port copies each object, at start-up, to its
segment:offset in the far-data arena (port/core/memory.c), so the host
branches that index ds[] see the initialized data segment.

Addresses come from port/gen/symbols.json (the placement map resolved by the
DOS fragment linker); sizes from compiling a probe that includes each data
module and prints sizeof of every exported object.

The port compiles the generated game/ tree, where some objects carry the
names of tools/game-renames.json; the identifiers are written with those
names (game/compat/aliases.json), the quoted names stay the reference ones.

Usage: port/tools/gen_ds_image.py [cc]
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def exported_objects(obj):
    out = subprocess.run(['nm', '-g', str(obj)], capture_output=True, text=True, check=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in 'DSBC':
            names.append(parts[2].lstrip('_') if sys.platform == 'darwin' else parts[2])
    return names


def main(argv):
    cc = argv[1] if len(argv) > 1 else 'cc'
    symbols = json.loads((ROOT/'port/gen/symbols.json').read_text())
    entries = []
    missing = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for src in sorted((ROOT/'src/main/data').glob('*.c')):
            obj = tmp/(src.stem + '.o')
            subprocess.run([cc, '-std=c99', '-I', str(ROOT/'src/common'), '-I', str(ROOT/'src/main/include'),
                            '-c', str(src), '-o', str(obj)], check=True)
            names = exported_objects(obj)
            probe = tmp/(src.stem + '_probe.c')
            body = '\n'.join(f'    printf("{n} %lu\\n", (unsigned long)sizeof({n}));' for n in names)
            probe.write_text(f'#include "{src}"\n#include <stdio.h>\nint main(void)\n{{\n{body}\n    return 0;\n}}\n')
            exe = tmp/(src.stem + '_probe')
            subprocess.run([cc, '-std=c99', '-w', '-I', str(ROOT/'src/common'), '-I', str(ROOT/'src/main/include'),
                            str(probe), '-o', str(exe)], check=True)
            sizes = dict(l.split() for l in subprocess.run([str(exe)], capture_output=True, text=True,
                                                            check=True).stdout.splitlines())
            for n in names:
                key = '_' + n if '_' + n in symbols else n
                if key not in symbols:
                    missing.append(f'{src.name}:{n}')
                    continue
                seg, off = symbols[key]
                entries.append((seg*16+off, int(sizes[n]), n, src.name, seg, off))
    entries.sort()
    aliases = json.loads((ROOT/'game/compat/aliases.json').read_text())['aliases']
    game_name = {v['old']: new for new, v in aliases.items()}
    overlaps = []
    for a, b in zip(entries, entries[1:]):
        if a[0]+a[1] > b[0]:
            overlaps.append(f'{a[2]} {a[0]:#x}+{a[1]:#x} overlaps {b[2]} {b[0]:#x}')
    lines = ['/* Generated by port/tools/gen_ds_image.py; do not edit.',
             ' * Original segment:offset placement of every object the recovered data',
             ' * modules (src/main/data) define. Only the addresses of these objects are',
             ' * taken here; their types and contents stay in the recovered sources. */',
             '#include "port.h"', '']
    for e in entries:
        lines.append(f'extern unsigned char {game_name.get(e[2], e[2])}[];')
    lines += ['', 'const PortImageObject port_image_objects[] = {']
    for linear, size, n, mod, seg, off in entries:
        lines.append(f'    {{ {game_name.get(n, n)}, 0x{seg:04x}u, 0x{off:04x}u, {size}u, "{n}" }}, /* {mod} */')
    lines += ['};', f'const unsigned port_image_object_count = {len(entries)};', '']
    (ROOT/'port/gen/data_image.c').write_text('\n'.join(lines))
    print(f'{len(entries)} objects; missing addresses: {missing}; overlaps: {len(overlaps)}')
    for o in overlaps:
        print('  ' + o)
    return 1 if overlaps else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
