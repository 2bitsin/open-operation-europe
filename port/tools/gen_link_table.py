#!/usr/bin/env python3
"""Generate port/gen/link_table.c: routine identifier -> native handler.

Every code symbol of the placement map (port/gen/symbols.json) gets an entry
so diagnostics can name any routine; entries whose routine has a
PORT_ROUTINE(name) handler somewhere under port/ point at it. Aliases (one
address, several names) share one entry; two handlers for one address fail.

Usage: port/tools/gen_link_table.py [output]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DGROUP = 18194


def main(argv):
    out = Path(argv[1]) if len(argv) > 1 else ROOT/'port/gen/link_table.c'
    symbols = json.loads((ROOT/'port/gen/symbols.json').read_text())
    by_address = {}
    by_name = {}
    for raw, (seg, off) in symbols.items():
        if seg == DGROUP:
            continue
        name = re.sub(r'^(\$@|@|_)', '', raw)
        address = seg*16+off
        by_address.setdefault(address, []).append(name)
        by_name[name] = address
    handlers = {}
    problems = []
    for path in sorted((ROOT/'port').rglob('*.c')):
        if 'build' in path.parts or path.parent.name == 'gen':
            continue
        text = re.sub(r'/\*.*?\*/', '', path.read_text(errors='replace'), flags=re.S)
        for m in re.finditer(r'^\s*PORT_ROUTINE\s*\(\s*(\w+)\s*\)\s*\{', text, re.M):
            name = m.group(1)
            if name not in by_name:
                problems.append(f'{path.relative_to(ROOT)}: PORT_ROUTINE({name}) names no routine of the placement map')
                continue
            address = by_name[name]
            if address in handlers:
                problems.append(f'{path.relative_to(ROOT)}: second handler {name} for {address:05x} ({handlers[address][0]})')
                continue
            handlers[address] = (name, path)
    lines = ['/* Generated by port/tools/gen_link_table.py; do not edit. */', '#include "port.h"', '']
    for address in sorted(handlers):
        lines.append(f'PORT_ROUTINE({handlers[address][0]});')
    lines += ['', 'const PortLink port_links[] = {']
    for address in sorted(by_address):
        if address in handlers:
            name = handlers[address][0]
            lines.append(f'    {{ 0x{address:05x}u, "{name}", port_routine_{name} }},')
        else:
            names = sorted(by_address[address])
            lines.append(f'    {{ 0x{address:05x}u, "{"/".join(names)}", NULL }},')
    lines += ['};', f'const unsigned port_link_count = {len(by_address)};', '']
    out.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(lines)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f'{len(handlers)} linked of {len(by_address)} routine identifiers')
    for p in problems:
        print('error: ' + p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
