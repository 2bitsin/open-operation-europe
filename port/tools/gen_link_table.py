#!/usr/bin/env python3
"""Generate port/gen/link_table.c: routine identifier -> native handler.

Every code symbol of the placement map (port/gen/symbols.json) gets an entry
so diagnostics can name any routine; entries whose routine has a
PORT_ROUTINE(name) handler point at it. Handlers of recovered routines are
generated into their game/ module (the native-build section, from
tools/game-services.json); handlers of native services live in
port/core/routines.c. A handler named after a renamed routine
(tools/game-renames.json) is found under its reference name through
game/compat/aliases.json. Aliases (one address, several names) share one
entry; two handlers for one address fail.

Usage: port/tools/gen_link_table.py [output] [game tree]
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DGROUP = 18194
AREAS = ('core', 'data', 'io', 'map', 'units')


def main(argv):
    out = Path(argv[1]) if len(argv) > 1 else ROOT/'port/gen/link_table.c'
    game = Path(argv[2]) if len(argv) > 2 else ROOT/'game'
    aliases = json.loads((game/'compat/aliases.json').read_text())['aliases']
    reference = {new: v['old'] for new, v in aliases.items()}
    symbols = json.loads((ROOT/'port/gen/symbols.json').read_text())
    by_address = {}
    by_name = {}
    for raw, (seg, off) in symbols.items():
        if seg == DGROUP:
            continue
        name = re.sub(r'^(\$@|@|_)', '', raw)
        address = seg*16+off
        by_address.setdefault(address, []).append(name)
        by_name[name] = address
    handlers = {}
    problems = []
    sources = [p for p in sorted((ROOT/'port').rglob('*.c')) if 'build' not in p.parts and p.parent.name != 'gen']
    sources += sorted(p for area in AREAS for p in (game/area).glob('*.c'))
    for path in sources:
        text = re.sub(r'/\*.*?\*/', '', path.read_text(errors='replace'), flags=re.S)
        for m in re.finditer(r'^\s*PORT_ROUTINE\s*\(\s*(\w+)\s*\)\s*\{', text, re.M):
            name = m.group(1)
            ref = reference.get(name, name)
            if ref not in by_name:
                problems.append(f'{path}: PORT_ROUTINE({name}) names no routine of the placement map')
                continue
            address = by_name[ref]
            if address in handlers:
                problems.append(f'{path}: second handler {name} for {address:05x} ({handlers[address][0]})')
                continue
            handlers[address] = (name, path)
    lines = ['/* Generated by port/tools/gen_link_table.py; do not edit. */', '#include "port.h"', '']
    for address in sorted(handlers):
        lines.append(f'PORT_ROUTINE({handlers[address][0]});')
    lines += ['', 'const PortLink port_links[] = {']
    for address in sorted(by_address):
        if address in handlers:
            name = handlers[address][0]
            lines.append(f'    {{ 0x{address:05x}u, "{reference.get(name, name)}", port_routine_{name} }},')
        else:
            names = sorted(by_address[address])
            lines.append(f'    {{ 0x{address:05x}u, "{"/".join(names)}", NULL }},')
    lines += ['};', f'const unsigned port_link_count = {len(by_address)};', '']
    out.parent.mkdir(parents=True, exist_ok=True)
    text = '\n'.join(lines)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f'{len(handlers)} linked of {len(by_address)} routine identifiers')
    for p in problems:
        print('error: ' + p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
