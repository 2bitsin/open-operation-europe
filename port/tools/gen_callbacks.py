#!/usr/bin/env python3
"""Generate port/gen/callbacks.h and port/gen/link_defaults.c.

Every recovered module whose host entry points take a service callback gets
one link callback per distinct callback type:

    link_<module>               when the module uses one callback type,
    link_<module>_<Typedef>     when it uses several.

callbacks.h declares them all (so any link file can pass any module's
callback to that module's routines). link_defaults.c defines the ones that no
file under port/link defines yet:
  - address-keyed callbacks `(uint8_t *, uint32_t, const uint16_t *, unsigned)`
    forward to the routine link table (port_service);
  - every other one stops with "module not linked" naming the service id.

Usage: port/tools/gen_callbacks.py --scan [cc]     refresh port/gen/callback_types.json (AST of src/main)
       port/tools/gen_callbacks.py [cc] [outdir]    write callbacks.h + link_defaults.c (default port/gen)
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AREAS = ('core', 'io', 'map', 'units', 'data')
sys.path.insert(0, str(Path(__file__).parent))
from gen_protos import STD, clean  # noqa: E402


def ast(path, cc):
    out = subprocess.run([cc, '-std=c99', '-I', str(ROOT/'src/common'), '-I', str(ROOT/'src/main/include'),
                          '-fsyntax-only', '-Xclang', '-ast-dump=json', str(path)],
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def fp_spelling(t):
    q = clean(t.get('desugaredQualType', t['qualType']))
    q = re.sub(r'\b([A-Za-z_]\w*)\s*\*', lambda m: m.group(0) if m.group(1) in STD else 'void *', q)
    return q


def callback_types(path, cc):
    """Distinct (typedef name, desugared function-pointer spelling) of callback parameters."""
    found = {}
    for node in ast(path, cc).get('inner', []):
        if node.get('kind') != 'FunctionDecl' or node.get('storageClass') == 'static':
            continue
        if not any(c.get('kind') == 'CompoundStmt' for c in node.get('inner', [])):
            continue
        for p in node.get('inner', []):
            if p.get('kind') != 'ParmVarDecl':
                continue
            t = p['type']
            spelled = fp_spelling(t)
            if '(*)' not in spelled:
                continue
            name = t['qualType'] if re.fullmatch(r'\w+', t['qualType']) else 'callback'
            found.setdefault(spelled, name)
    return found


def declarator(spelling, name):
    m = re.fullmatch(r'(.*?)\(\*\)\s*\((.*)\)', spelling)
    ret, params = m.group(1).strip(), m.group(2).strip()
    return ret, params, f'{ret} {name}({params})'


def scan(cc):
    table = []
    for area in AREAS:
        for path in sorted((ROOT/'src/main'/area).glob('*.c')):
            types = callback_types(path, cc)
            if types:
                table.append({'area': area, 'module': path.stem, 'types': [[s, n] for s, n in types.items()]})
    (ROOT/'port/gen/callback_types.json').write_text(json.dumps(table, indent=1) + '\n')
    print(f'{len(table)} modules with callbacks')
    return 0


def main(argv):
    if len(argv) > 1 and argv[1] == '--scan':
        return scan(argv[2] if len(argv) > 2 else 'cc')
    outdir = Path(argv[2]) if len(argv) > 2 else ROOT/'port/gen'
    table = json.loads((ROOT/'port/gen/callback_types.json').read_text())
    defined = set()
    for path in (ROOT/'port/link').rglob('*.c'):
        text = re.sub(r'/\*.*?\*/', '', path.read_text(errors='replace'), flags=re.S)
        for m in re.finditer(r'^[A-Za-z_][\w \*]*?\b(link_\w+)\s*\([^;{]*\)\s*\{', text, re.M):
            defined.add(m.group(1))
    header = ['/* Generated by port/tools/gen_callbacks.py; do not edit. */',
              '#ifndef PORT_GEN_CALLBACKS_H', '#define PORT_GEN_CALLBACKS_H', '#include <stdint.h>', '']
    defaults = ['/* Generated by port/tools/gen_callbacks.py; do not edit.',
                ' * Fallback callbacks for modules without a port/link file yet. */',
                '#include "port.h"', '#include "callbacks.h"', '']
    count = 0
    for entry in table:
            area = entry['area']
            path = Path(entry['module'] + '.c')
            types = dict(entry['types'])
            many = len(types) > 1
            for spelled, tname in types.items():
                cname = f'link_{path.stem}_{tname}' if many else f'link_{path.stem}'
                ret, params, decl = declarator(spelled, cname)
                header.append(f'{decl}; /* {area}/{path.name} {tname} */')
                count += 1
                if cname in defined:
                    continue
                plist = [p.strip() for p in params.split(',')] if params and params != 'void' else []
                names = [f'a{i}' for i in range(len(plist))]
                sig = ', '.join(f'{t} {n}' if '(*)' not in t else t.replace('(*)', f'(*{n})') for t, n in zip(plist, names))
                address_keyed = len(plist) == 4 and plist[1] == 'uint32_t' and 'uint16_t *' in plist[2]
                defaults.append(f'{ret} {cname}({sig or "void"})')
                defaults.append('{')
                if address_keyed and ret == 'uint16_t':
                    defaults.append(f'    return port_service({names[0]}, {names[1]}, {names[2]}, {names[3]});')
                elif address_keyed and ret == 'uint32_t':
                    defaults.append(f'    return port_call({names[0]}, {names[1]}, {names[2]}, {names[3]});')
                else:
                    for n in names:
                        defaults.append(f'    (void){n};')
                    idarg = names[1] if len(names) > 1 else '0'
                    if 'uint8_t *' in (plist[1] if len(plist) > 1 else '') or (len(plist) > 2 and plist[1].endswith('*')):
                        idarg = names[2] if len(names) > 2 else '0'
                    defaults.append(f'    port_unhandled("{path.stem} (no link file)", (unsigned)({idarg}), 0);')
                    if ret != 'void':
                        defaults.append(f'    return 0;')
                defaults.append('}')
                defaults.append('')
    header += ['', '#endif', '']
    outdir.mkdir(parents=True, exist_ok=True)
    for name, lines in (('callbacks.h', header), ('link_defaults.c', defaults)):
        out = outdir/name
        text = '\n'.join(lines)
        if not out.exists() or out.read_text() != text:
            out.write_text(text)
    print(f'{count} module callbacks; {len(defined)} link_ functions defined under port/link')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
