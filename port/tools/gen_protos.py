#!/usr/bin/env python3
"""Generate port/gen/recovered.h: prototypes of every external function the
recovered host branches define, so the port's link layer is type-checked
against the actual recovered definitions.

Types come from clang's AST of each module compiled exactly as the
validators compile it. Module-local struct/union types are passed only by
pointer in these host branches; they are written as `void *` (same ABI), and
function-pointer parameters are written in their desugared form.

Usage: port/tools/gen_protos.py [cc]
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AREAS = ('core', 'io', 'map', 'units', 'data')


def decls(path, cc):
    out = subprocess.run([cc, '-std=c99', '-I', str(ROOT/'src/common'), '-I', str(ROOT/'src/main/include'),
                          '-fsyntax-only', '-Xclang', '-ast-dump=json', str(path)],
                         capture_output=True, text=True, check=True).stdout
    tree = json.loads(out)
    for node in tree.get('inner', []):
        if node.get('kind') != 'FunctionDecl':
            continue
        if node.get('storageClass') == 'static':
            continue
        if not any(c.get('kind') == 'CompoundStmt' for c in node.get('inner', [])):
            continue   # declaration only; the definition lives elsewhere
        loc = node.get('loc', {})
        if 'includedFrom' in loc or loc.get('file', str(path)) != str(path):
            pass
        yield node


def clean(t):
    """Rewrite a clang type string so it names only standard types."""
    t = t.strip()
    t = re.sub(r'(const\s+)?(struct|union)\s+\(unnamed[^)]*\)\s*\*', lambda m: (m.group(1) or '') + 'void *', t)
    t = re.sub(r'(const\s+)?(struct|union)\s+\w+\s*\*', lambda m: (m.group(1) or '') + 'void *', t)
    return t


STD = {'void', 'char', 'short', 'int', 'long', 'unsigned', 'signed', 'const', 'volatile', 'float', 'double',
       'uint8_t', 'uint16_t', 'uint32_t', 'int8_t', 'int16_t', 'int32_t', 'size_t', 'restrict', '_Bool'}


def param_type(p):
    t = p['type']
    q = t.get('desugaredQualType', t['qualType'])
    q = clean(q)
    if '(*)' in q:
        q = re.sub(r'\b([A-Za-z_]\w*)\s*\*', lambda m: m.group(0) if m.group(1) in STD else 'void *', q)
    words = set(re.findall(r'[A-Za-z_]\w*', q))
    unknown = words - STD
    if unknown:
        # a typedef'd struct pointer whose desugared spelling still names it
        if q.rstrip().endswith('*') and '(' not in q:
            return ('const ' if q.lstrip().startswith('const') else '') + 'void *'
        q2 = clean(t['qualType'])
        if not (set(re.findall(r'[A-Za-z_]\w*', q2)) - STD):
            return q2
        return None
    return q


def main(argv):
    cc = argv[1] if len(argv) > 1 else 'cc'
    lines = ['/* Generated by port/tools/gen_protos.py from the recovered host branches.',
             ' * Do not edit: regenerate after src/main changes. */',
             '#ifndef PORT_GEN_RECOVERED_H', '#define PORT_GEN_RECOVERED_H',
             '#include <stdint.h>', '#include <stddef.h>', '']
    problems = []
    seen = set()
    for area in AREAS:
        for path in sorted((ROOT/'src/main'/area).glob('*.c')):
            lines.append(f'/* {area}/{path.name} */')
            for node in decls(path, cc):
                name = node['name']
                if name in seen:
                    continue
                seen.add(name)
                ftype = node['type']['qualType']
                ret = ftype[:ftype.index('(')].strip()
                ret = clean(ret)
                if set(re.findall(r'[A-Za-z_]\w*', ret)) - STD:
                    ret = re.sub(r'\b([A-Za-z_]\w*)\s*\*', lambda m: m.group(0) if m.group(1) in STD else 'void *', ret)
                params = [c for c in node.get('inner', []) if c.get('kind') == 'ParmVarDecl']
                ptypes = []
                ok = True
                for p in params:
                    pt = param_type(p)
                    if pt is None:
                        ok = False
                        problems.append(f'{path.name}: {name}: parameter type {p["type"]}')
                        break
                    ptypes.append(pt)
                variadic = node.get('variadic', False) or '...' in ftype
                if not ok:
                    lines.append(f'/* {name}: not representable, see gen_protos problems */')
                    continue
                plist = ', '.join(ptypes) if ptypes else 'void'
                if variadic:
                    plist += ', ...'
                if re.search(r'\(\*\)', ret):
                    lines.append(f'/* {name}: returns a function pointer; not emitted */')
                    continue
                lines.append(f'{ret} {name}({plist});')
            lines.append('')
    lines.append('#endif')
    (ROOT/'port/gen').mkdir(parents=True, exist_ok=True)
    (ROOT/'port/gen/recovered.h').write_text('\n'.join(lines) + '\n')
    print(f'{len(seen)} prototypes; {len(problems)} problems')
    for p in problems:
        print('  ' + p)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
